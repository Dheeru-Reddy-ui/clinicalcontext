"""Write ``docs/EVAL.md`` from the eval artifacts (Phase 14.6).

The methodology is prose and lives here; every *number* in the document is
read from ``evals/results/*.json`` at generation time and stamped with the
run that produced it. A document that restates measurements by hand starts
lying the next time a runner is run, so this one is regenerated instead:

    uv run python -m scripts.eval_doc
"""

from __future__ import annotations

import argparse
import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

RESULTS = Path(__file__).resolve().parents[1] / "evals" / "results"
OUT = Path(__file__).resolve().parents[2] / "docs" / "EVAL.md"


def load(name: str) -> dict[str, Any] | None:
    path = RESULTS / name
    if not path.is_file():
        return None
    payload: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    return payload


def pct(value: float | None, digits: int = 1) -> str:
    return "—" if value is None else f"{value * 100:.{digits}f}%"


def num(value: float | None, digits: int = 3) -> str:
    return "—" if value is None else f"{value:.{digits}f}"


def when(payload: dict[str, Any] | None) -> str:
    return str((payload or {}).get("generated_at", ""))[:10] or "not run"


def render() -> str:
    golden = load("golden.json")
    ablation = load("ablation.json")
    calibration = load("calibration.json")
    voice = load("voice.json")
    load_test = load("load.json")

    lines: list[str] = [
        "# Evaluation",
        "",
        "How this system is measured, how the ground truth was built, and what the",
        "measurements currently say.",
        "",
        f"*Generated by `uv run python -m scripts.eval_doc` on "
        f"{datetime.now(UTC):%Y-%m-%d}. Every number below is read from the result",
        "file its runner wrote, with that run's date beside it — nothing here is",
        "typed in, and re-running a runner changes this document.*",
        "",
        "## Why a golden set at all",
        "",
        "A retrieval system can be made to look good by choosing the questions after",
        "seeing the answers. The defence is ground truth that was fixed before the",
        "pipeline ran and derived from something other than the pipeline: here, from",
        "what human indexers at PubMed decided each paper is about.",
        "",
        "## How the ground truth was built",
        "",
        "`evals/golden/build.py` derives the set from the corpus and records provenance",
        "on every item:",
        "",
        "- **Questions** instantiate the generic clinical question types of Ely et al.",
        "  (BMJ 1999) — drug of choice, is drug X indicated in situation Y, adverse",
        "  effects, prognosis, diagnostic accuracy, guideline recommendation,",
        "  head-to-head comparison — over the topics the corpus covers, plus questions",
        "  on topics it does **not** cover, where the correct behaviour is to abstain.",
        "- **Relevant documents** are those PubMed's indexers assigned the question's",
        "  MeSH headings *and* whose own title and conclusion address that kind of",
        "  question. Co-indexing two headings is not an answer, and a paper *about*",
        "  guidelines is not a guideline.",
        "- **Relevant passages** are those documents' structured-abstract Conclusions.",
        "- **The reference answer** is the authors' own conclusion from the",
        "  highest-authority relevant document, attributed by PMID. It is not a",
        "  model-written gold answer.",
        "- **Expected abstentions** come from topics deliberately outside the corpus.",
        "",
        "Only MeSH-indexed documents can be labelled, so retrieval is scored over that",
        "labelable universe rather than the whole corpus — scoring against documents",
        "that could never have been labelled would report misses that are not misses.",
        "",
        "The set grows from real use: a thumbs-down marked *wrong* or *unsupported*",
        "is queued for review (`golden_reviews`), and a reviewer promotes it with",
        "`python -m evals.golden.promote`, writing the reference answer by hand.",
        "",
        "## What is measured, and separately",
        "",
        "**Retrieval is scored before generation is scored.** recall@k, precision@k,",
        "MRR and nDCG@10 are computed against the labelled passages and documents,",
        "with no reference to what the answer said. A regression can then be placed in",
        "the layer it came from instead of being averaged away.",
        "",
        "**Generation** is scored two ways. Deterministic signals always: whether a",
        "gold passage was cited, whether it abstained when it should have, lexical",
        "grounding support, evidence-grade match, contradiction precision and recall.",
        "RAGAS (faithfulness, answer relevance, context precision and recall) and a",
        "clinical rubric run behind an `AnswerJudge` protocol when an Anthropic key is",
        "configured; without one the report records `ran: false` rather than an",
        "invented score.",
        "",
        "**Safety** is its own suite of adversarial cases, and the voice harness plays",
        "the same cases aloud so guardrail parity is measured rather than assumed.",
        "",
        "**Calibration** asks whether the stated confidence means anything: each level",
        "has a nominal probability, and the reliability curve compares it to observed",
        "accuracy (on the golden set, and against thumbs feedback in production).",
        "",
    ]

    if golden:
        g = golden["golden"]
        r = golden["retrieval"]
        gen = golden["generation"]
        corpus = golden["corpus"]
        backend = golden["backend"]
        lines += [
            "## The current numbers",
            "",
            f"Golden set: **{g['items']} items**, run {when(golden)} on the",
            f"`{backend['ai_backend']}` backend ({backend['reasoner']} reasoner,",
            f"{backend['embedder']} embedder, {backend['reranker']} reranker) against a",
            f"corpus of {corpus['documents']:,} documents "
            f"({corpus['labelable_documents']:,} labelable).",
            "",
            "### Retrieval, scored alone",
            "",
            "| Level | recall@5 | recall@10 | precision@10 | MRR | nDCG@10 |",
            "|---|---|---|---|---|---|",
            f"| Passages | {num(r['chunks']['recall_at_5'])} | "
            f"{num(r['chunks']['recall_at_10'])} | {num(r['chunks']['precision_at_10'])} | "
            f"{num(r['chunks']['mrr'])} | {num(r['chunks']['ndcg_at_10'])} |",
            f"| Documents | {num(r['documents']['recall_at_5'])} | "
            f"{num(r['documents']['recall_at_10'])} | {num(r['documents']['precision_at_10'])} | "
            f"{num(r['documents']['mrr'])} | {num(r['documents']['ndcg_at_10'])} |",
            "",
            "These are low, and they are the honest measurement of a lexical-hashing",
            "embedder with a BM25 reranker — the offline stand-ins for Cohere",
            "embed-v4.0 and rerank-v3.5. The same harness against the cloud backend is",
            "the number that would matter for a deployment; it has not been run because",
            "there is no key in this environment.",
            "",
            "### Generation",
            "",
            "| Signal | Value |",
            "|---|---|",
            "| Abstained when the corpus could not answer | "
            f"{pct(gen['abstained_when_expected'])} |",
            f"| Abstained when it could have answered | {pct(gen['abstained_when_answerable'])} |",
            f"| Answers citing a gold passage | {pct(gen['cited_gold_rate'])} |",
            f"| Evidence grade matched the expected one | {pct(gen['grade_match_rate'])} |",
            f"| Lexical grounding support | {pct(gen['grounding_support_mean'])} |",
            f"| Contradiction precision / recall | {pct(gen['contradiction']['precision'])} / "
            f"{pct(gen['contradiction']['recall'])} |",
            f"| Graph latency p50 / p95 | {gen['latency_ms']['p50']} / "
            f"{gen['latency_ms']['p95']} ms |",
            "",
        ]
        safety = golden.get("safety", {})
        if safety:
            lines += [
                "### Safety",
                "",
                f"**{safety['total_passed']}/{safety['total']} adversarial cases pass** "
                f"({pct(safety['overall_rate'], 0)}), gate "
                f"{'passed' if safety['gate_passed'] else 'FAILED'}. By category:",
                "",
                "| Category | Passed |",
                "|---|---|",
            ]
            for name, case in sorted(safety.get("categories", {}).items()):
                lines.append(f"| {name.replace('_', ' ')} | {case['passed']}/{case['total']} |")
            lines.append("")

    if ablation:
        lines += [
            "### Ablation — what each stage is worth",
            "",
            f"The golden set through every configuration, one stage at a time "
            f"(run {when(ablation)}).",
            "",
            "| # | Configuration | recall@10 (passages) | recall@10 (documents) | MRR | "
            "faithfulness | abstained | cited gold |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for row in ablation.get("rows", []):
            # Rows 9 and 10 are scored on the PICO-eligible subset only.
            subset = " *(PICO subset)*" if row.get("subset") == "pico" else ""
            lines.append(
                f"| {row.get('config', '')} | {row.get('description', '')}{subset} | "
                f"{num(row.get('recall_at_10'))} | {num(row.get('recall_at_10_documents'))} | "
                f"{num(row.get('mrr'))} | {num(row.get('faithfulness'))} | "
                f"{pct(row.get('abstained_when_answerable'), 0)} | "
                f"{pct(row.get('cited_gold_rate'), 0)} |"
            )
        lines.append("")

    if calibration:
        curve = calibration.get("curves", {}).get("golden", {})
        rec = calibration.get("recommendation", {})
        lines += [
            "### Calibration",
            "",
            f"Golden set, outcome *{curve.get('outcome', 'cited gold')}*, "
            f"n={curve.get('n')} (run {when(calibration)}): "
            f"Brier {num(curve.get('brier'))}, ECE {num(curve.get('ece'))}.",
            "",
            "| Stated | n | Means | Observed |",
            "|---|---|---|---|",
        ]
        for bucket in curve.get("buckets", []):
            lines.append(
                f"| {bucket['level']} | {bucket['n']} | {pct(bucket['predicted'], 0)} | "
                f"{pct(bucket.get('observed'), 0)} |"
            )
        lines += [
            "",
            f"**Retune {'recommended' if rec.get('retune') else 'not needed'}.** "
            "The script proposes; a person changes the thresholds in the confidence",
            "assessor, in a reviewed commit, and the next run says whether it worked.",
            "",
        ]
        for reason in rec.get("reasons", []):
            lines.append(f"- {reason}")
        lines.append("")

    if voice:
        summary = voice.get("summary", {})
        first = summary.get("first_audio", {}).get("server", {}).get("total_first_audio", {})
        gate = voice.get("gate", {})
        failing = [c["name"] for c in gate.get("checks", []) if c.get("passed") is False]
        lines += [
            "### Voice",
            "",
            f"{summary.get('fixtures', '—')} spoken fixtures through the real WebSocket "
            f"pipeline at real-time pace (run {when(voice)}), "
            f"{summary.get('backend', {}).get('stt', '')} → "
            f"{summary.get('backend', {}).get('tts', '')}:",
            "",
            f"- First audio **p50 {first.get('p50')} ms / p95 {first.get('p95')} ms** "
            "(target p50 ≤ 1200, p95 ≤ 2000)",
            f"- {len(gate.get('checks', [])) - len(failing)}/{len(gate.get('checks', []))} "
            "gate checks pass at the full level",
        ]
        if failing:
            lines.append(f"- Failing: {', '.join(failing)} — both properties of the offline")
            lines.append("  speech stack, not regressions; see VERIFICATION.md")
        lines.append("")

    if load_test:
        sustained = load_test.get("sustained", {})
        total = sustained.get("total", {})
        breaking = load_test.get("breaking_point")
        lines += [
            "### Load",
            "",
            f"{sustained.get('users')} concurrent simulated clinicians for "
            f"{sustained.get('seconds')} s against {load_test.get('target')} "
            f"(run {when(load_test)}, {load_test.get('machine', {}).get('cpu_count')} CPUs): "
            f"{total.get('requests')} requests, error rate {pct(total.get('error_rate'), 1)}, "
            f"{total.get('rps')} req/s.",
            "",
            "Breaking point: "
            + (
                f"**{breaking['users']} users** — {breaking['reason']}"
                if breaking
                else "not reached within the ramp"
            )
            + f"; last stage that held, {load_test.get('capacity_users')} users.",
            "",
        ]

    lines += [
        "## The CI gate",
        "",
        "The `golden-gate` job loads a corpus snapshot into its own Postgres, embeds",
        "it locally, and runs the golden set on every pull request. It fails when",
        "recall@10 or faithfulness drops more than two points against the committed",
        "baseline, and unconditionally on any PHI or diagnosis-refusal miss. The",
        "snapshot exists because GitHub Actions cannot hold the corpus; the baseline",
        "is produced the same way, so the comparison is snapshot to snapshot.",
        "",
        "## Reproducing all of it",
        "",
        "```bash",
        "uv run python -m evals.golden.run          # retrieval, generation, calibration, safety",
        "uv run python -m evals.ablation.full       # the configuration table",
        "uv run python -m evals.golden.calibrate    # reliability curves and the retune advice",
        "uv run python -m evals.voice.run --in-process   # the spoken harness",
        "uv run python -m evals.load.run            # the load test (needs the API up)",
        "uv run python -m scripts.eval_doc          # rewrite this document from the results",
        "```",
        "",
        "Everything lands in `backend/evals/results/*.json`, which is what the public",
        "[methodology page](../frontend/app/methodology/page.tsx) reads at request",
        "time. Change an eval, re-run it, redeploy, and the published numbers change.",
        "",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
